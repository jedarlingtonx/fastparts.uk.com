    legacyCookies: [],        // old site's cookie names to delete on every page load, whatever the visitor chose, e.g. ["PHPSESSID", "wordpress_*"]. ["*"] = every cookie except those kept (see keepCookies)
    cookies: {},              // optional cookie lists shown under each category in the settings panel: { analytics: [{ name, duration, purpose }], ... }. The banner's own cookie and Google's (when gaId is set) are listed automatically.
    showCookieLists: true,    // false = no cookie lists in the panel
