/*
  Pixel North cookie control kit, engine 4.4.2.
  DO NOT EDIT THIS FILE PER SITE. Every site's settings live in consent-config.js.

  - Four optional categories (analytics, preferences, media, marketing), switched on or
    off per site in consent-config.js. Essential cookies are always on and need no consent.
  - Nothing optional runs until the visitor says yes. Reject is as easy as Accept.
  - Google Analytics (GA4) is built in. Anything else is gated in the page with
    data-consent="<category>" (see README.md) or with onAccept/onReject hooks.
  - The choice can be changed at any time from any element marked data-cookie-settings.
*/
